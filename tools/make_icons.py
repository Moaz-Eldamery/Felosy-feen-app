"""Render the Spending app icon: system blue field, white rising pace line over a dashed on-track line."""
import sys
from PIL import Image, ImageDraw

OUT = sys.argv[1]
SS = 4  # supersample


def render(size):
    S = size * SS
    img = Image.new("RGB", (S, S), (0, 122, 255))
    d = ImageDraw.Draw(img)
    # subtle top-to-bottom tone so the field isn't flat
    for y in range(S):
        t = y / S
        r = int(10 * (1 - t))
        g = int(132 - 22 * t)
        b = int(255 - 18 * t)
        d.line([(0, y), (S, y)], fill=(r, g, b))

    def P(x, y):
        return (x * S, y * S)

    # dashed on-track line
    x0, y0, x1, y1 = 0.2, 0.74, 0.8, 0.26
    n = 9
    for i in range(n):
        a = i / n
        b2 = a + 0.55 / n
        d.line([P(x0 + (x1 - x0) * a, y0 + (y1 - y0) * a), P(x0 + (x1 - x0) * b2, y0 + (y1 - y0) * b2)],
               fill=(255, 255, 255, 255), width=int(0.022 * S))
    # spending line (solid), drawn twice for a soft white halo + crisp line
    pts = [(0.2, 0.74), (0.33, 0.71), (0.45, 0.65), (0.55, 0.64), (0.66, 0.55)]
    w = int(0.06 * S)
    d.line([P(*p) for p in pts], fill=(255, 255, 255), width=w, joint="curve")
    for p in pts[:1] + pts[-1:]:
        cx, cy = P(*p)
        rr = w / 2
        d.ellipse([cx - rr, cy - rr, cx + rr, cy + rr], fill=(255, 255, 255))
    # today dot
    cx, cy = P(*pts[-1])
    R = 0.075 * S
    d.ellipse([cx - R, cy - R, cx + R, cy + R], fill=(255, 255, 255))
    R2 = 0.04 * S
    d.ellipse([cx - R2, cy - R2, cx + R2, cy + R2], fill=(0, 112, 245))
    return img.resize((size, size), Image.LANCZOS)


for name, size in [("icon-512.png", 512), ("icon-192.png", 192), ("apple-touch-icon.png", 180)]:
    im = render(size)
    im.info["Description"] = "Spending app icon, generated by make_icons.py (PIL, procedural)."
    from PIL import PngImagePlugin
    meta = PngImagePlugin.PngInfo()
    meta.add_text("Source", "Procedurally drawn with Pillow by Claude Code (make_icons.py); no image model, no stock asset.")
    im.save(f"{OUT}/{name}", pnginfo=meta)
